"""Generate version_info.txt (the Windows version resource) from clickwave/common.py APP_VERSION,
so the version number lives in exactly one place.

Run directly, or imported by Clickwave.spec:  py tools/make_version_info.py
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEMPLATE = """# Windows version resource for Clickwave.exe (generated by tools/make_version_info.py - do not edit).
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({tuple}),
    prodvers=({tuple}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'Clickwave'),
        StringStruct('FileDescription', 'Clickwave - click sounds for your inputs'),
        StringStruct('FileVersion', '{full}'),
        StringStruct('InternalName', 'Clickwave'),
        StringStruct('OriginalFilename', 'Clickwave.exe'),
        StringStruct('ProductName', 'Clickwave'),
        StringStruct('ProductVersion', '{version}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def read_version():
    with open(os.path.join(ROOT, "clickwave", "common.py"), encoding="utf-8") as f:
        m = re.search(r'^APP_VERSION\s*=\s*"([0-9.]+)"', f.read(), re.M)
    if not m:
        raise SystemExit("APP_VERSION not found in clickwave/common.py")
    return m.group(1)


def write(path=None):
    version = read_version()
    parts = [int(p) for p in version.split(".")][:4]
    parts += [0] * (4 - len(parts))
    text = TEMPLATE.format(tuple=", ".join(map(str, parts)), full=".".join(map(str, parts)), version=version)
    path = path or os.path.join(ROOT, "version_info.txt")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return version


if __name__ == "__main__":
    print("version_info.txt ->", write())
